"""Removing a runner from the party."""
import asyncio, json, sys, os, re, zipfile
from playwright.async_api import async_playwright
from harness import *
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        gm=await page(b,"GM","gm.html")
        await gm.click("nav [data-act=tab][data-t=map]");await gm.click(".ms [data-act=map-add-blank]");await gm.wait_for_timeout(200)
        await gm.evaluate("hostOnline()");await gm.wait_for_timeout(900)
        code=await gm.evaluate("inviteCode()")
        p1=await page(b,"P1","player.html");await make_runner(p1,"Razor")
        p2=await page(b,"P2","player.html");await make_runner(p2,"Kilo")
        await join(p1,code,"Alex","Razor");await join(p2,code,"Sam","Kilo");await gm.wait_for_timeout(400)
        cid=await p1.evaluate("Net.charId")
        await gm.evaluate("id=>{addPcToEnc(id);save()}",cid)
        ok(await gm.evaluate("st.party.length")==2,"two runners in the party")
        # remove from the party table
        await gm.click("nav [data-act=tab][data-t=party]");await gm.wait_for_timeout(200)
        await gm.click(f"[data-act=ask-remove-pc][data-id='{cid}']");await gm.wait_for_timeout(200)
        t=await gm.inner_text(".modal")
        ok("razor" in t.lower() and "played by Alex" in t and "at the table now" in t,"confirmation names the runner and player")
        ok("comes off the map" in t and "current encounter" in t and "disconnected" in t,"it lists what will happen")
        await gm.screenshot(path=OUT+'/'+"rm-modal.png")
        ok(await gm.is_disabled("#rm-go"),"remove button starts locked")
        await gm.fill("#rm-confirm","razr");ok(await gm.is_disabled("#rm-go"),"wrong text keeps it locked")
        await gm.fill("#rm-confirm","razor");ok(not await gm.is_disabled("#rm-go"),"typing the handle unlocks it")
        await gm.click("#rm-go");await gm.wait_for_timeout(700)
        g=await gm.evaluate("id=>({party:st.party.map(c=>c.handle),tok:st.maps.some(m=>m.tokens.some(t=>t.ref===id)),enc:st.encounter.list.some(x=>x.ref===id),roster:Object.values(st.roster).map(r=>r.name),conns:Host.conns.size,v:meta.vlist[0]&&meta.vlist[0].label})",cid)
        ok(g["party"]==["Kilo"],"runner removed from the party")
        ok(not g["tok"] and not g["enc"],"token and encounter entry removed")
        ok(g["roster"]==["Sam"] and g["conns"]==1,"player removed from the roster and disconnected")
        ok("Before removing Razor" in (g["v"] or ""),"restore point saved first")
        ok(await p1.evaluate("Net.state==='off'") and "removed your runner from the party" in await p1.inner_text("#app"),"player told they were removed and can rejoin")
        ok(await p1.evaluate("id=>S.chars.has(id)",cid),"player keeps their own copy")
        await p2.wait_for_timeout(300)
        ok(await p2.evaluate("Net.scene.tokens.length===1&&Net.players.length===1"),"other players see the token and player gone")
        # rejoin without a block: comes back
        await join(p1,code,"Alex","Razor");await gm.wait_for_timeout(400)
        ok(await gm.evaluate("st.party.length")==2,"without a block, rejoining adds them back")
        # remove with block from the host window
        await gm.click("[data-act=open-modal][data-m=host] >> nth=0");await gm.wait_for_timeout(200)
        await gm.click(f".modal [data-act=ask-remove-pc][data-id='{cid}']");await gm.wait_for_timeout(200)
        await gm.check("#rm-block");await gm.fill("#rm-confirm","Razor");await gm.press("#rm-confirm","Enter");await gm.wait_for_timeout(600)
        ok(await gm.evaluate("st.party.length===1&&st.host.banned.length===1"),"removed and blocked (Enter confirms)")
        ok("removed you from this table" in await p1.inner_text("#app"),"blocked player told they're removed")
        await join(p1,code,"Alex","Razor");await gm.wait_for_timeout(400)
        ok(await gm.evaluate("st.party.length")==1 and await p1.evaluate("Net.state==='off'"),"a blocked player can't rejoin")
        await gm.click("[data-act=open-modal][data-m=host] >> nth=0");await gm.wait_for_timeout(200)
        ok("Alex" in await gm.inner_text(".modal"),"blocked list shows the player")
        await gm.screenshot(path=OUT+'/'+"rm-blocked.png")
        await gm.click("[data-act=unblock]");await gm.wait_for_timeout(200)
        await join(p1,code,"Alex","Razor");await gm.wait_for_timeout(400)
        ok(await gm.evaluate("st.party.length")==2,"after unblocking they can rejoin")
        # undo via version history
        await gm.evaluate("()=>{ui.modal=null;renderModal()}")
        await b.close()
asyncio.run(main())
sys.exit(finish())
