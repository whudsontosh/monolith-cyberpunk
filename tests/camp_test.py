"""Campaigns: several per game, switching, hosting the open one, backups, delete and restore."""
import asyncio, json, sys
from playwright.async_api import async_playwright
from harness import *

def state_of(name_or_id): return f"(()=>{{const x=campsAll();const e=x.list.find(c=>c.id==='{name_or_id}'||c.name==='{name_or_id}');return e?JSON.parse(localStorage.getItem('monolith-campaign-'+e.id+'-state')):null}})()"
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={"width":1440,"height":900})
        await ctx.add_init_script(SHIM)
        boot=await ctx.new_page();await boot.goto(APP+"launcher.html");await boot.evaluate("localStorage.clear()");await boot.close()
        gm=await ctx_page(ctx,"GM","gm.html")
        x=await gm.evaluate("campsAll()")
        ok(len(x["list"])==1 and x["list"][0]["game"]=="cyberpunk" and x["list"][0]["ruleset"]=="cp2020" and x["list"][0]["gameVersion"]==MANIFEST["version"],"first campaign is created and tagged with game, ruleset and version")
        ok(await gm.evaluate("st.campaign.name")=="Night City Campaign","first campaign named by the game")
        ok(await gm.evaluate("ui.tab")=="party","single campaign skips the picker")
        await gm.evaluate("()=>{st.campaign.name='Old Crew';st.campaign.notes='secret';st.npcs.push({id:'n1',name:'Fixer Joe',type:'Street',stats:{INT:5,REF:5,TECH:5,COOL:5,ATTR:5,LUCK:5,MA:5,BODY:5,EMP:5},skills:[],weapons:[],armor:{},custom:true});const c=normalizeChar({...clone(SAMPLE),id:uid(),handle:'Spike'});st.party.push(c);persist();render()}")
        pw1=await gm.evaluate("st.host.password")
        ok("old crew" in (await gm.inner_text("nav .campsw")).lower(),"nav shows the open campaign")
        await gm.click("nav .campsw");await gm.wait_for_timeout(200)
        ok(await gm.locator(".camp-card.is-open").count()==1,"campaigns screen lists the open campaign")
        ok("spike" in (await gm.inner_text(".camp-card.is-open .camp-crew")).lower(),"card shows the crew")
        await gm.screenshot(path=OUT+"/c-list1.png")
        await gm.fill("#camp-new-name","The Arasaka Job");await gm.check("#camp-new-npcs")
        async with gm.expect_navigation():
            await gm.click("[data-act=camp-create]")
        await gm.wait_for_function("()=>typeof st!=='undefined'&&st&&st.campaign",timeout=8000);await gm.wait_for_timeout(500)
        ok(await gm.evaluate("st.campaign.name")=="The Arasaka Job","new campaign is open after create")
        ok(await gm.evaluate("st.party.length")==0,"new campaign has an empty party")
        ok(await gm.evaluate("st.npcs.length")==1,"custom NPCs copied (a game option on the new-campaign card)")
        ok(await gm.evaluate("ui.tab")=="party","switch lands on the party, not the picker")
        pw2=await gm.evaluate("st.host.password");ok(pw2 and pw2!=pw1,"new campaign has its own password")
        old=await gm.evaluate(state_of("Old Crew"))
        ok(old["campaign"]["name"]=="Old Crew" and len(old["party"])==1,"old campaign untouched in storage")
        await gm.evaluate("()=>{st.campaign.notes='arasaka notes';const c=normalizeChar({...clone(SAMPLE),id:uid(),handle:'Ghost'});st.party.push(c);persist();snapshot('test',true)}")
        await gm.wait_for_timeout(4600)
        gm2=await ctx_page(ctx,"GM2","gm.html")
        ok(await gm2.evaluate("ui.tab")=="campaigns","launch with 2 campaigns opens the picker")
        ok(await gm2.locator(".camp-card:not(.camp-new)").count()==2,"picker lists both campaigns")
        await gm2.close()
        vl=await gm.evaluate("meta.vlist.map(v=>v.scope)");cur=await gm.evaluate("CUR")
        ok(len(vl)>0 and all(s=="camp:"+cur for s in vl),"version history scoped to the open campaign")
        await gm.click("nav .campsw");await gm.wait_for_timeout(200)
        async with gm.expect_navigation():
            await gm.click(".camp-card:has-text('Old Crew') [data-act=camp-open]")
        await gm.wait_for_function("()=>typeof st!=='undefined'&&st&&st.campaign",timeout=8000);await gm.wait_for_timeout(500)
        ok(await gm.evaluate("st.campaign.name")=="Old Crew" and await gm.evaluate("st.party.map(c=>c.handle).join()")=="Spike","switched back: Old Crew with its party")
        ok(await gm.evaluate("st.campaign.notes")=="secret","Old Crew notes intact")
        await gm.evaluate("hostOnline()");await gm.wait_for_timeout(900)
        ok(await gm.evaluate("Host.status")=="online","hosting Old Crew")
        await gm.evaluate("ui.modal='host';renderModal()");await gm.wait_for_timeout(100)
        ok("old crew" in (await gm.inner_text(".campline")).lower(),"host window names the campaign")
        await gm.evaluate("ui.modal=null;renderModal()")
        code=await gm.evaluate("inviteCode()")
        pl=await page(b,"P","player.html")
        await make_runner(pl,"Rattler")
        await join(pl,code,"Ana","Rattler")
        ok(await gm.evaluate("Host.conns.size")==1,"player joined Old Crew")
        await gm.click("nav .campsw");await gm.wait_for_timeout(200)
        ok("hosting" in (await gm.inner_text(".camp-card.is-open")).lower(),"open card shows hosting")
        await gm.click(".camp-card:has-text('Arasaka') [data-act=camp-host]");await gm.wait_for_timeout(200)
        ok(await gm.evaluate("ui.modal")=="camp-switch","switching while hosting asks first")
        async with gm.expect_navigation():
            await gm.click("[data-act=camp-switch-go]")
        await gm.wait_for_function("()=>typeof st!=='undefined'&&st&&st.campaign",timeout=8000);await gm.wait_for_timeout(1500)
        ok(await gm.evaluate("st.campaign.name")=="The Arasaka Job","now on Arasaka")
        ok(await gm.evaluate("Host.status")=="online","Open & host went online automatically")
        ok(await gm.evaluate("ui.modal")=="host","host window open")
        inv=await gm.evaluate("readInvite(inviteCode())")
        ok(inv and inv.get("n")=="The Arasaka Job" and inv.get("p")==pw2 and inv.get("g")=="cyberpunk","invite carries the campaign, its password and the game")
        pstate=await pl.evaluate("Net.state")
        ok(pstate!="online","player from the old table was disconnected ("+str(pstate)+")")
        old=await gm.evaluate(state_of("Old Crew"))
        ok(any(c.get("handle")=="Rattler" for c in old["party"]),"joined player saved into Old Crew")
        ok(await gm.evaluate("st.party.every(c=>c.handle!=='Rattler')"),"Arasaka party unaffected")
        await gm.evaluate("ui.modal=null;renderModal()")
        bk=await gm.evaluate("JSON.parse(sessionStorage.getItem('__bk')||'{}')")
        ok(any(k.startswith("cyberpunk-campaign-old-crew-") for k in bk) and any(k.startswith("cyberpunk-campaign-the-arasaka-job-") for k in bk),"desktop backup files per campaign, named by game")
        await gm.click("nav .campsw");await gm.wait_for_timeout(200)
        await gm.click(".camp-card:has-text('Old Crew') [data-act=camp-rename]");await gm.wait_for_timeout(100)
        await gm.fill("#camp-rename-in","Old Crew Redux");await gm.press("#camp-rename-in","Enter");await gm.wait_for_timeout(150)
        ok((await gm.evaluate(state_of("Old Crew Redux")))["campaign"]["name"]=="Old Crew Redux","rename a closed campaign")
        await gm.click(".camp-card:has-text('Old Crew Redux') [data-act=camp-dup]");await gm.wait_for_timeout(200)
        ok(await gm.locator(".camp-card:has-text('Old Crew Redux (copy)')").count()==1,"duplicate")
        async with gm.expect_download() as dl:
            await gm.click(".camp-card:has-text('Old Crew Redux (copy)') [data-act=camp-dl]")
        d=await dl.value;path=OUT+"/dl.json";await d.save_as(path)
        j=json.load(open(path));ok(j["format"]=="monolith-campaign" and j["game"]=="cyberpunk" and j["ruleset"]=="cp2020" and j["state"]["campaign"]["name"]=="Old Crew Redux (copy)" and len(j["state"]["party"])==2,"download a closed campaign")
        await gm.click(".camp-card:has-text('Old Crew Redux (copy)') [data-act=camp-ask-del]");await gm.wait_for_timeout(150)
        ok(await gm.is_disabled("#camp-del-go"),"delete disabled until confirmed")
        await gm.fill("#camp-del-in","old crew redux");ok(await gm.is_disabled("#camp-del-go"),"partial name not accepted")
        await gm.fill("#camp-del-in","old crew redux (copy)");ok(not await gm.is_disabled("#camp-del-go"),"full name accepted")
        await gm.click("#camp-del-go");await gm.wait_for_timeout(800)
        ok(await gm.locator(".camp-card:has-text('Old Crew Redux (copy)')").count()==0,"deleted")
        ok(await gm.locator("[data-act=camp-undelete]").count()==1,"in recently deleted")
        await gm.click("[data-act=camp-undelete]");await gm.wait_for_timeout(500)
        ok(await gm.locator(".camp-card:has-text('Old Crew Redux (copy)')").count()==1,"restored from recently deleted")
        ok(await gm.locator(".camp-card.is-open [data-act=camp-ask-del]").count()==0,"can't delete the open campaign")
        await gm.set_input_files("#file-in",path);await gm.wait_for_timeout(400)
        ok(await gm.evaluate("ui.modal")=="gm-import","campaign backup asks add vs replace")
        await gm.click("[data-act=gm-import-new]");await gm.wait_for_timeout(300)
        n=await gm.evaluate("campsLoad().list.length");ok(n==4,"import added a campaign (%d)"%n)
        ok(await gm.evaluate("st.campaign.name")=="The Arasaka Job","import didn't touch the open campaign")
        await gm.set_input_files("#file-in",path);await gm.wait_for_timeout(400)
        await gm.click("[data-act=gm-import-replace]");await gm.wait_for_timeout(300)
        ok(await gm.evaluate("st.campaign.name")=="Old Crew Redux (copy)","replace still works")
        other=OUT+"/other-game.json";json.dump({**j,"game":"dnd"},open(other,"w"))
        await gm.set_input_files("#file-in",other);await gm.wait_for_timeout(400)
        ok(await gm.evaluate("ui.modal")!="gm-import","a campaign from another game is refused")
        await gm.click("nav .campsw");await gm.wait_for_timeout(200)
        await gm.set_viewport_size({"width":390,"height":844});await gm.wait_for_timeout(200)
        await gm.screenshot(path=OUT+"/c-phone.png",full_page=True)
        sw=await gm.evaluate("document.documentElement.scrollWidth");ok(sw<=390,"no sideways scroll at phone width (%d)"%sw)
        await b.close()
    sys.exit(finish())
asyncio.run(main())
