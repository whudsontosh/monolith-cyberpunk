"""Item explanations in the shop and on the sheet."""
import asyncio, json, sys
from playwright.async_api import async_playwright
from harness import *
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        pg=await page(b,"P","player.html");pg.set_default_timeout(6000)
        await pg.click(".card-foot >> text=Copy to my runners");await pg.wait_for_timeout(200)
        await pg.click("nav [data-act=go-roster]");await pg.click(".card:has-text('Razor') >> text=Open sheet");await pg.wait_for_timeout(300)
        miss=await pg.evaluate("[...WEAPONS.filter(w=>!WEAPON_NOTES[w[0]]).map(w=>w[0]),...ARMOR.filter(a=>!ARMOR_NOTES[a[0]]).map(a=>a[0]),...CYBER.filter(x=>!CYBER_NOTES[x[0]]).map(x=>x[0]),...GEAR.filter(g=>!GEAR_NOTES[g[0]]).map(g=>g[0])]")
        ok(not miss,"every catalog item has an explanation %s"%miss)
        bad=await pg.evaluate("""(()=>{const out=[];for(const [k,L] of [['w',WEAPONS],['a',ARMOR],['c',CYBER],['g',GEAR]])L.forEach((_,i)=>{try{const h=itemInfoHTML(k+':'+i);if(!h||/undefined|NaN/.test(h))out.push(k+i+':'+(h||'empty').match(/.{0,40}(undefined|NaN).{0,40}/)?.[0])}catch(e){out.push(k+i+' '+e.message)}});return out})()""")
        ok(not bad,"all %d explanations render with no gaps %s"%(await pg.evaluate("WEAPONS.length+ARMOR.length+CYBER.length+GEAR.length"),bad[:5]))
        # shop hover
        await pg.evaluate("ui.modal='shop';ui.shopTab='Weapons';renderModal()");await pg.wait_for_timeout(200)
        row=pg.locator(".shop-row").nth(8)
        await row.hover();await pg.wait_for_timeout(300)
        ok(await pg.is_visible("#shop-detail .ii-pane"),"hovering a weapon shows its explanation")
        t=(await pg.inner_text("#shop-detail")).lower()
        ok("to hit" in t and "+ 1d10" in t and "damage" in t and "range" in t and "jams" in t,"weapon card covers to-hit, damage, range, reliability")
        exp=await pg.evaluate("(()=>{const c=curChar(),k=calc(c);return k.eff.REF+skillLevel(c,'Handgun')+WEAPONS[8][2]+(k.smart?2:0)})()")
        ok(("%d + 1d10"%exp) in t,"to-hit number is worked out for this runner (%d)"%exp)
        ok(await pg.evaluate("ItemTip.inPane===true&&!document.querySelector('.itemtip:not([hidden])')"),"on a wide screen it shows in the shop's details pane, covering nothing")
        await pg.screenshot(path=OUT+'/'+"weapon.png")
        await pg.mouse.move(5,5);await pg.wait_for_timeout(200);ok("armalite" in (await pg.inner_text("#shop-detail")).lower(),"pane keeps the last item when the pointer leaves")
        await pg.click("[data-act=shop-tab][data-t=Armor]");await pg.wait_for_timeout(150)
        await pg.locator(".shop-row").nth(5).hover();await pg.wait_for_timeout(300)
        t=(await pg.inner_text("#shop-detail")).lower();ok("sp 18" in t and "ref" in t and "→" in t,"armor card shows SP change and REF penalty for this runner")
        await pg.screenshot(path=OUT+'/'+"armor.png")
        await pg.click("[data-act=shop-tab][data-t=Cyberware]");await pg.wait_for_timeout(150)
        await pg.locator(".shop-row:has-text('Kerenzikov boost +2')").hover();await pg.wait_for_timeout(300)
        t=(await pg.inner_text("#shop-detail")).lower();ok("+2 initiative" in t and "humanity" in t and "→ about" in t,"cyberware card: effect and Humanity/EMP impact")
        await pg.screenshot(path=OUT+'/'+"cyber.png")
        await pg.click("[data-act=shop-tab][data-t=Gear]");await pg.wait_for_timeout(150)
        await pg.locator(".shop-row:has-text('Trauma kit')").hover();await pg.wait_for_timeout(300)
        ok("medical tech" in (await pg.inner_text("#shop-detail")).lower(),"gear card")
        # keyboard
        await pg.mouse.move(5,5);await pg.wait_for_timeout(100)
        await pg.locator(".shop-row:has-text('Medkit') .t").focus();await pg.wait_for_timeout(100)
        ok("first aid" in (await pg.inner_text("#shop-detail")).lower(),"keyboard focus shows the explanation")
        await pg.set_viewport_size({"width":900,"height":800});await pg.wait_for_timeout(200)
        await pg.locator(".shop-row:has-text('Medkit')").hover();await pg.wait_for_timeout(300)
        ok(await pg.is_visible("#itemtip") and not await pg.is_visible("#shop-detail"),"narrower window: floating card instead of the pane")
        await pg.screenshot(path=OUT+'/'+"narrow.png")
        await pg.keyboard.press("Escape");await pg.wait_for_timeout(100)
        ok(not await pg.is_visible("#itemtip") and await pg.evaluate("ui.modal")=="shop","Escape closes the card first, not the shop")
        await pg.set_viewport_size({"width":1440,"height":900})
        # buying still works with the card up
        await pg.locator(".shop-row:has-text('Medkit')").hover();await pg.wait_for_timeout(250)
        n0=await pg.evaluate("curChar().gear.length")
        await pg.locator(".shop-row:has-text('Gas mask') [data-act=buy]").click();await pg.wait_for_timeout(150)
        ok(await pg.evaluate("curChar().gear.some(g=>g.name==='Gas mask')"),"Buy still works")
        await pg.keyboard.press("Escape");await pg.keyboard.press("Escape");await pg.wait_for_timeout(150)
        ok(not await pg.is_visible("#itemtip"),"closing the shop hides the card")
        # sheet items
        await pg.click("[data-act=tab][data-t=gear]") if await pg.locator("[data-act=tab][data-t=gear]").count() else None
        tabs=await pg.evaluate("[...document.querySelectorAll('[data-act=tab],[data-act=sheet-tab]')].map(b=>b.dataset.t)")
        print("tabs",tabs)
        await pg.wait_for_timeout(200)
        cnt=await pg.locator(".it[data-info]").count();print("sheet items with info",cnt)
        if cnt==0:
            for t_ in tabs:
                await pg.click(f"[data-t='{t_}']");await pg.wait_for_timeout(150)
                if await pg.locator(".it[data-info]").count():break
        it=pg.locator(".it[data-info]").first
        ok(await it.count()==1,"owned items on the sheet have cards")
        await it.locator(".t").hover();await pg.wait_for_timeout(300)
        ok(await pg.is_visible("#itemtip"),"hovering an owned item shows its card")
        await pg.screenshot(path=OUT+'/'+"sheet.png")
        # touch: tap to pin
        await b.close()
        b=await p.chromium.launch();ctx=await b.new_context(viewport={"width":390,"height":844},has_touch=True,is_mobile=True);await ctx.add_init_script(SHIM)
        pg=await ctx_page(ctx,"phone","player.html");pg.set_default_timeout(6000)
        await pg.tap(".card-foot >> text=Copy to my runners");await pg.wait_for_timeout(200)
        await pg.tap("nav [data-act=go-roster]");await pg.tap(".card:has-text('Razor') >> text=Open sheet");await pg.wait_for_timeout(300)
        await pg.evaluate("ui.modal='shop';ui.shopTab='Weapons';renderModal()");await pg.wait_for_timeout(200)
        await pg.locator(".shop-row .t").nth(2).tap();await pg.wait_for_timeout(200)
        ok(await pg.is_visible("#itemtip"),"tapping a name shows the card on a phone")
        r=await pg.evaluate("(()=>{const r=document.getElementById('itemtip').getBoundingClientRect();return [r.left,r.right,r.top,r.bottom]})()")
        ok(r[0]>=0 and r[1]<=390 and r[2]>=0 and r[3]<=844,"card fits the phone screen %s"%r)
        await pg.screenshot(path=OUT+'/'+"phone.png")
        await pg.tap("[data-ii-close]");await pg.wait_for_timeout(150)
        ok(not await pg.is_visible("#itemtip"),"close button hides it")
        await pg.locator(".shop-row .t").nth(3).tap();await pg.wait_for_timeout(150);await pg.tap(".modal-h h2");await pg.wait_for_timeout(150)
        ok(not await pg.is_visible("#itemtip"),"tapping elsewhere hides it")
        await b.close()
asyncio.run(main())
sys.exit(finish())
