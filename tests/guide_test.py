"""Guided build, the delete check and recently deleted."""
import asyncio, json, sys
from playwright.async_api import async_playwright
from harness import *
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        ctx=await b.new_context(viewport={"width":1440,"height":900},reduced_motion="reduce");await ctx.add_init_script(SHIM)
        pg=await ctx_page(ctx,"P","player.html")
        await pg.click(".roster-head >> text=New runner");await pg.wait_for_timeout(200)
        await pg.screenshot(path=OUT+'/'+"g-choose.png")
        ok(await pg.locator(".buildopt.rec").count()==1,"first-time players see Guided build recommended")
        await pg.click(".buildopt >> text=Guided build");await pg.wait_for_timeout(300)
        ok(await pg.evaluate("curChar().guide===true&&ui.view==='wizard'"),"guided build starts the wizard with explanations on")
        ok(await pg.locator(".guide-step .tip").count()==1,"step 1 explains handles, roles and concept")
        ok(await pg.locator(".role .hint").count()==10,"each role shows its best stats")
        await pg.fill("#w-handle","Vex");await pg.click("button.role:has-text('Netrunner')");await pg.wait_for_timeout(200)
        await pg.screenshot(path=OUT+'/'+"g-step1.png")
        await pg.click("text=Next: Stats");await pg.wait_for_timeout(200)
        t=await pg.inner_text(".guide-step");ok("Netrunner" in t and "INT, TECH, REF" in t,"stats step names the Netrunner's key stats")
        ok(await pg.locator(".stat .hint").count()==9,"every stat is explained")
        await pg.screenshot(path=OUT+'/'+"g-step2.png")
        await pg.click("text=Next: Career skills");await pg.wait_for_timeout(200)
        ok(await pg.locator(".sk .hint").count()==10,"every career skill (incl. Interface) is explained")
        ok("Interface" in await pg.inner_text(".guide-step"),"career step explains the special ability")
        await pg.screenshot(path=OUT+'/'+"g-step3.png")
        await pg.click("text=Next: Pickup skills");await pg.wait_for_timeout(200)
        h=await pg.evaluate("[...document.querySelectorAll('.sk .hint')].map(e=>e.textContent).filter(t=>/Martial Art|triple/.test(t)||/trained fighting/.test(t))")
        ok(any("triple IP" in x for x in h),"multiplier skills say they cost more IP")
        for st in ["Next: Lifepath","Next: Funds & gear","Next: Review"]:
            await pg.click("text="+st);await pg.wait_for_timeout(150)
        ok(await pg.locator(".guide-step").count()==1,"review step has its guide")
        await pg.click("text=Finish character");await pg.wait_for_timeout(300)
        ok(await pg.locator(".tip").count()>=4,"finished sheet shows tips (stats, wounds, armor, tab)")
        await pg.screenshot(path=OUT+'/'+"g-sheet.png")
        await pg.click(".tabs button:has-text('Combat')");await pg.wait_for_timeout(150)
        ok("Initiative" in await pg.inner_text("#app"),"combat tab tip explains initiative, attacks and damage")
        await pg.click("[data-act=toggle-guide] >> nth=0");await pg.wait_for_timeout(150)
        ok(await pg.locator(".tip").count()==0,"Hide tips removes them")
        await pg.click("[data-act=toggle-guide] >> nth=0");await pg.wait_for_timeout(150)
        ok(await pg.locator(".tip").count()>=4,"Show tips brings them back")
        # quick build has no explanations but can toggle on
        await pg.click("nav [data-act=go-roster]");await pg.click(".roster-head >> text=New runner");await pg.click(".buildopt >> text=Quick build");await pg.wait_for_timeout(200)
        ok(await pg.locator(".guide-step").count()==0,"quick build has no explanations")
        await pg.click("text=Explain the rules");await pg.wait_for_timeout(150)
        ok(await pg.locator(".guide-step").count()==1,"explanations can be switched on mid-build")
        # delete with security check
        await pg.click("nav [data-act=go-roster]");await pg.wait_for_timeout(150)
        n0=await pg.evaluate("S.chars.size")
        await pg.click(".card:has-text('Vex') [data-act=ask-delete]");await pg.wait_for_timeout(200)
        ok(await pg.is_disabled("#del-go"),"delete button starts locked")
        await pg.fill("#del-confirm","vx");ok(await pg.is_disabled("#del-go"),"wrong text keeps it locked")
        await pg.evaluate("Dice.check('x',1)");await pg.wait_for_timeout(200)   # trigger a re-render while typing
        ok(await pg.is_disabled("#del-go"),"still locked after a background redraw")
        await pg.fill("#del-confirm","VEX");await pg.wait_for_timeout(100)
        ok(not await pg.is_disabled("#del-go"),"typing the handle (any case) unlocks it")
        await pg.screenshot(path=OUT+'/'+"g-delete.png")
        await pg.click("#del-go");await pg.wait_for_timeout(300)
        ok(await pg.evaluate("S.chars.size")==n0-1 and not await pg.evaluate("[...S.chars.values()].some(c=>c.handle==='Vex')"),"runner deleted")
        ok(await pg.evaluate("S.trash.some(t=>t.data.handle==='Vex')"),"it's in Recently deleted")
        await pg.click("nav [data-m=backups]");await pg.wait_for_timeout(200);await pg.click("[data-act=trash-restore]");await pg.wait_for_timeout(200)
        ok(await pg.evaluate("[...S.chars.values()].some(c=>c.handle==='Vex')"),"and it can be restored")
        # draft discard (no handle -> type DELETE)
        await pg.click("[data-act=close-modal]");await pg.wait_for_timeout(100)
        dr=await pg.evaluate("[...S.chars.values()].find(c=>!c.created&&!c.handle).id")
        await pg.evaluate("id=>{ui.charId=id;ui.view='wizard';render()}",dr);await pg.wait_for_timeout(150)
        await pg.click("text=Discard draft");await pg.wait_for_timeout(150)
        ok("DELETE" in await pg.inner_text(".modal"),"an unnamed draft asks you to type DELETE")
        await pg.fill("#del-confirm","delete");await pg.press("#del-confirm","Enter");await pg.wait_for_timeout(300)
        ok(not await pg.evaluate("id=>S.chars.has(id)",dr) and await pg.evaluate("ui.view==='roster'"),"draft discarded with Enter, back on roster")
        await b.close()
asyncio.run(main())
sys.exit(finish())
